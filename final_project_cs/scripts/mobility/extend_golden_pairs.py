def meters(a, b):
    dy = (b[0] - a[0]) * 111320
    dx = (b[1] - a[1]) * 111320 * math.cos(math.radians((a[0] + b[0]) / 2))
    return math.hypot(dx, dy)


def bucket(d):
    return "short" if d < 4000 else "mid" if d < 9000 else "long"


def main() -> int:
    doc = json.loads(PAIRS.read_text(encoding="utf-8"))
    pairs = doc["pairs"]
    have = {frozenset((p["a"], p["b"])) for p in pairs}
    count = {k: sum(1 for p in pairs if p["bucket"] == k) for k in TARGET}
    rng = random.Random(SEED + len(pairs))
    names = sorted(PLACES)
    tries = 0
    while any(count[k] < TARGET[k] for k in TARGET) and tries < 200000:
        tries += 1
        a, b = rng.sample(names, 2)
        d = meters(PLACES[a], PLACES[b])
        if d < 1500 or d >= 18000:
            continue
        k = bucket(d)
        if count[k] >= TARGET[k] or frozenset((a, b)) in have:
            continue
        have.add(frozenset((a, b)))
        count[k] += 1
        pairs.append({"a": a, "alat": PLACES[a][0], "alon": PLACES[a][1], "b": b, "blat": PLACES[b][0], "blon": PLACES[b][1],
                      "straight_m": round(d), "bucket": k, "origin": "2026-10-07 확장(시드 고정)"})
    for i, p in enumerate(pairs, 1):
        p.setdefault("id", f"G{i:02d}")                 # 앞 40개의 번호(G01~G40)는 그대로 — 카카오 값 파일이 그 번호로 묶여 있다
    doc["note"] = ("카카오 대조용 장소 쌍 — 장소 이름·좌표만(카카오 값은 없다). 카카오 값은 datasets/mobility/raw/kakao_golden/ 에 따로(약관상 저장소 밖). "
                   "규모 근거: scripts/mobility/extend_golden_pairs.py 머리말.")
    PAIRS.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(len(pairs), count)
    return 0


