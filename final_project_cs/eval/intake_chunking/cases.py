def build(plan: tuple[str, str, list[str], list[list[tuple[str, list[tuple[str, str, bool]]]]]]) -> dict[str, Any]:
    """한 건 → `{id, note, text, gold_items, line_gold}` — 정답 장소는 원문에 글자 그대로 있어야 한다(검사)."""
    case_id, note, preface, days = plan
    lines: list[str] = list(preface)
    items: list[dict[str, Any]] = []
    for index, day in enumerate(days):
        lines.append(HEADS[index])
        for line, places in day:
            lines.append(line)
            for place, kind, optional in places:
                if place not in line:
                    raise ValueError(f"{case_id}: 정답 장소가 원문에 없다 — {place!r} / {line!r}")
                items.append({"day": index + 1, "date": DATES[index], "start": None, "end": None, "place": place,
                              "kind": kind, "canon": [], "optional": optional, "line": len(lines)})
    return {"case_id": case_id, "note": note, "text": "\n".join(lines), "today": TODAY,
            "gold": {"items": items, "moves": [], "conditions": [], "preferences": [], "requests": ["register"],
                     "requests_optional": [], "missing": [], "missing_optional": [], "trip": {}}}


def all_cases() -> list[dict[str, Any]]:
    return [build(plan) for plan in PLANS]


