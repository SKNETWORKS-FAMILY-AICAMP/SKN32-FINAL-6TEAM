def tag(x, y, kind):
    """상태 꼬리표 — 구현 · 진행 중 · 예정 · 검토 중"""
    cls, t = {"done": ("tg-done", "구현"), "wip": ("tg-wip", "진행 중"), "plan": ("tg-plan", "예정"), "look": ("tg-plan", "검토 중")}[kind]
    w = 14 + len(t) * 13
    R(x, y - 13, w, 18, cls, 9)
    T(x + w / 2, y + 1, t, "tg-t")
    return w


