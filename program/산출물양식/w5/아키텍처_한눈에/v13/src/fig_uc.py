def _chip(f, x, y, w, text):
    f.node_svg.append(f'<rect x="{x}" y="{y}" width="{w}" height="24" rx="4" fill="rgba(47,91,216,0.06)" '
                      f'stroke="{LINK}" stroke-width="1" stroke-dasharray="5,3"/>'
                      f'<text x="{x + w / 2:g}" y="{y + 16}" class="lab" fill="{LINK}">{text}</text>')


def _dot(f, name, cx, cy):
    """합류점 — r=6 점. 검사용으로 16×16 상자로 등록한다"""
    f.nodes[name] = (cx - 8, cy - 8, 16, 16, "dot")
    f.node_svg.append(f'<circle cx="{cx}" cy="{cy}" r="6" fill="#6b7488"/>')


