def _is_standard(term):
    """팀이 붙인 이름 · 시험 자료 이름 · 우리 구성 요소가 아니면 표준 용어로 보고 「용어 정의」 표에서 뺀다."""
    return not any(k in term for k in PROJECT)


def load(key):
    f = DIR / f"{key}.json"
    if not f.exists():
        return {"rewrites": [], "glossary": []}
    return json.loads(f.read_text(encoding="utf-8"))


def _cells(old, new):
    """표 한 줄(| a | b |)로 받은 다시 쓰기를 칸 단위 쌍으로 나눈다."""
    o, n = old.strip(), new.strip()
    if o.startswith("●"):
        # 글머리표 줄: 문서 블록에서는 「라벨:」과 글이 따로 있다 → 라벨 뒤 글끼리 바꾼다
        o, n = o.lstrip("● ").strip(), n.lstrip("● ").strip()
        if ": " in o and ": " in n:
            lo, ro = o.split(": ", 1)
            ln, rn = n.split(": ", 1)
            out = [(ro, rn)]
            if lo != ln:
                out.append((lo + ":", ln + ":"))
            return out
        return [(o, n)]
    if not (o.startswith("|") and n.startswith("|")):
        out = [(old, new)]
        io, jn = o.find(": "), n.find(": ")
        if 0 < io < 30 and 0 < jn < 30:  # 라벨이 따로 있는 글머리표일 수 있다
            out.append((o[io + 2:], n[jn + 2:]))
            if o[:io] != n[:jn]:
                out.append((o[:io + 1], n[:jn + 1]))
        return out
    a = [c.strip() for c in old.strip().strip("|").split("|")]
    b = [c.strip() for c in new.strip().strip("|").split("|")]
    if len(a) != len(b):
        return []
    return [(x, y) for x, y in zip(a, b) if x and x != y]


def pairs(key):
    out = []
    for r in load(key)["rewrites"]:
        new = r["new"]
        for a, b in DEGLOSS:
            new = new.replace(a, b)
        out += _cells(r["old"], new)
    return out


def run_blocks(secs, key, rewrites=True, glossary_before="first"):
    """docx 빌더용. secs = 절 목록(블록 목록의 목록). 돌려줌: (secs, 못 찾은 원문 수).
    「용어 정의」 표는 1절의 「1.2」 제목 앞(없으면 1절 끝)에 넣는다 — 개요를 읽은 뒤, 본문 전에."""
    cfg = load(key)
    secs = [[list(b) if isinstance(b, tuple) else b for b in s] for s in secs]
    miss = []
    if rewrites:
        secs, miss = P.rewrite(secs, pairs(key))
    secs = P.strip_refs(secs)
    secs = P.terms(secs, TERMS)
    rows = [list(r) for r in cfg.get("glossary", []) if not _is_standard(r[0])] + [list(r) for r in EXTRA.get(key, [])]
    body = _text(secs)
    have = " ".join(r[0] for r in rows)
    for k, v in COMMON:
        if k in body and k.rstrip("=") not in have:
            rows.append([k.rstrip("="), v])
    if rows:
        g = P.terms(P.glossary(rows), TERMS)
        s = secs[0]
        # 맨 앞(첫 소제목 앞)에 둔다 — 본문의 낯선 말을 읽기 전에 볼 수 있게
        k = 0 if glossary_before is None else next((i for i, x in enumerate(s) if x[0] == "h"), 0)
        s[k:k] = g
    return secs, miss


def glossary_rows(key, body):
    rows = [[run_text(a), run_text(b)] for a, b in load(key).get("glossary", []) if not _is_standard(a)] + [list(r) for r in EXTRA.get(key, [])]
    have = " ".join(r[0] for r in rows)
    for k, v in COMMON:
        if k in body and k.rstrip("=") not in have:
            rows.append([k.rstrip("="), v])
    return rows


def apply_raw(text, key):
    """마크다운 원문에 문장 다시 쓰기만 한다(6주차 초안용). 그림 줄(![..](경로))은 건드리지 않는다 — 파일 이름이 바뀌면 그림을 못 찾는다.
    표 칸에서 나온 짧은 조각(4글자 미만)은 다른 낱말 속까지 바꿀 수 있어 쓰지 않는다."""
    ps = [(o, n) for o, n in pairs(key) if len(o) >= 4]
    out = []
    for line in text.splitlines():
        if not line.lstrip().startswith("!["):
            for o, n in ps:
                line = line.replace(o, n)
        out.append(line)
    return chr(10).join(out)


def run_text(t, key=None, _cache={}):
    """한 문자열(엑셀 칸 등)용."""
    if key not in _cache:
        _cache[key] = pairs(key) if key else []
    for o, n in _cache[key]:
        if o in t:
            t = t.replace(o, n)
    t = P.terms([["p", t]], TERMS)[0][1]
    t = P.strip_refs([["p", t]])[0][1]
    return t
