def esc(x):
    return html.escape(x)


def table(head, rows, cls=""):
    th = "".join(f"<th>{esc(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f'<table class="{cls}"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>'


def fig():
    t = FIG.read_text(encoding="utf-8")
    css = re.search(r"<style>(.*?)</style>", t, flags=re.S).group(1)
    css = re.sub(r"body\{[^}]*\}|\.wrap\{[^}]*\}", "", css)
    return css, re.search(r'(<div class="diagram">.*</div>)</div></body>', t, flags=re.S).group(1)


