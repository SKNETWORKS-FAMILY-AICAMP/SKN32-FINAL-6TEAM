def full(s):
    uid, name, head, main, ext, var, qual, open_ = s
    rows = "".join(f"<tr><th>{esc(k)}</th><td>{esc(v).replace(chr(10), '<br>')}</td></tr>" for k, v in head)
    ol = "<ol>" + "".join(f"<li>{esc(x)}</li>" for x in main) + "</ol>"
    ex = "".join(f'<div class="ext d{min(len(n) - 2, 2)}"><b>{esc(n)}</b> {esc(t)}</div>' for n, t in ext)
    ul = lambda xs: "<ul>" + "".join(f"<li>{esc(x)}</li>" for x in xs) + "</ul>" if xs else "<p class='note'>없음</p>"
    return (f'<section class="spec" id="{uid}"><h3><span>{uid}</span> {esc(name)}</h3>'
            f'<table class="head">{rows}</table>'
            f'<div class="flows"><div><h4>주 성공 시나리오</h4>{ol}</div><div><h4>확장</h4>{ex}</div></div>'
            f'<div class="flows"><div><h4>기술 · 데이터 변형</h4>{ul(var)}<h4>품질 · 자율성 · 빈도</h4>{ul(qual)}</div>'
            f'<div><h4>미결 사항</h4>{ul(open_)}</div></div></section>')


def casual(s):
    uid, name, ctx, body, ext = s
    li = "".join(f"<li>{esc(x)}</li>" for x in ext)
    return (f'<section class="spec casual" id="{uid}"><h3><span>{uid}</span> {esc(name)}</h3>'
            f'<p class="note">{esc(ctx)}</p><p>{esc(body)}</p>'
            + (f'<h4>확장</h4><ul>{li}</ul>' if ext else "") + "</section>")


