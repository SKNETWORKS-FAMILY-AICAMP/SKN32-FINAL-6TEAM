def esc(x):
    return html.escape(x)


def table(head, rows):
    th = "".join(f"<th>{esc(h)}</th>" for h in head)
    tr = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>"


def spec(s):
    uid, name, summ, who, sup, pre, post, basic, alt, exc = s
    li = lambda xs: "<ol>" + "".join(f"<li>{esc(x)}</li>" for x in xs) + "</ol>"
    ul = lambda xs: "<ul>" + "".join(f"<li>{esc(x)}</li>" for x in xs) + "</ul>"
    return (f'<section class="spec" id="{uid}"><h3><span>{uid}</span> {esc(name)}</h3>'
            f'<p class="sum">1. 개요 — {esc(summ)}</p>'
            f'<table class="rel"><tr><th>개시자</th><td>{esc(who)}</td><th>지원자</th><td>{esc(sup)}</td></tr>'
            f'<tr><th>사전 조건</th><td colspan="3">{esc(pre)}</td></tr><tr><th>사후 조건</th><td colspan="3">{esc(post)}</td></tr></table>'
            f'<div class="flows"><div><h4>3. 기본 흐름</h4>{li(basic)}</div>'
            f'<div><h4>4. 대안 흐름</h4>{ul(alt)}</div><div><h4>5. 예외 흐름</h4>{ul(exc)}</div></div></section>')


