def scr(sid, name, route, purpose, elements, server, status, imgs):
    """화면 한 장의 블록 묶음."""
    out = [("h", f"{sid} {name}")]
    out.append(("t", ["항목", "내용"],
                [["주소", route], ["하는 일", purpose], ["상태", status]], [1, 5]))
    out.append(("b", "주요 요소:", "", 0))
    for e in elements:
        out.append(("b", "", e, 1))
    out.append(("b", "서버 연결:", "", 0))
    for s in server:
        out.append(("b", "", s, 1))
    for path, cap in imgs:
        out.append(("img", str(path), cap))
    return out


