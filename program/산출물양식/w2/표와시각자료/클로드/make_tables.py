def won(x):
    return "{:,.0f}원".format(x)


def unit(p):
    """상품 하나의 단위경제를 계산해 dict 로 돌려준다."""
    net = p["가격"] / P["VAT"] * (1 - p["환불"])
    fee = p["가격"] * p["결제"]
    costs = {"결제 수수료": fee}
    if "사용량" in p:
        u = p["사용량"]
        costs["장소 상세"] = u["장소상세"] * P["단가_장소상세_usd"] * P["환율"]
        costs["장소 검색"] = u["장소검색"] * P["단가_장소검색_usd"] * P["환율"]
        costs["경로 요소"] = u["경로요소"] * P["단가_경로요소_usd"] * P["환율"]
    costs.update(p["고정원가"])
    var = sum(costs.values())
    return {"순매출": net, "원가": costs, "변동비": var, "기여I": net - var}


