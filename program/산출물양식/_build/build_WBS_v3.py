def read_requirement_ids():
    # 요구사항 빌드 스크립트는 실행하지 않고 원천 GROUPS만 읽는다.
    assert REQ_SOURCE.is_file(), f"요구사항 원천 없음: {REQ_SOURCE}"
    tree = ast.parse(REQ_SOURCE.read_text(encoding="utf-8-sig"))
    nodes = [
        node for node in tree.body
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "GROUPS"
                for target in node.targets)
    ]
    assert len(nodes) == 1, "요구사항 GROUPS 원천을 하나로 특정할 수 없음"
    groups = ast.literal_eval(nodes[0].value)
    source_ids = [
        item[0]
        for _, _, sections in groups
        for _, rows in sections
        for item in rows
    ]
    assert source_ids, "요구사항 원천 ID가 비어 있음"
    assert len(source_ids) == len(set(source_ids)), "요구사항 원천 ID 중복"
    assert all(re.fullmatch(r"REQ-\d{3,}", value) for value in source_ids), \
        "요구사항 ID 형식 오류"

    assert REQ_BOOK.is_file(), f"요구사항 생성본 없음: {REQ_BOOK}"
    req_wb = openpyxl.load_workbook(REQ_BOOK, read_only=True, data_only=False)
    try:
        book_ids = [
            row[3]
            for row in req_wb.active.iter_rows(values_only=True)
            if len(row) > 3 and isinstance(row[3], str)
            and re.fullmatch(r"REQ-\d{3,}", row[3])
        ]
    finally:
        req_wb.close()
    assert len(book_ids) == len(set(book_ids)), "요구사항 생성본 ID 중복"
    assert set(source_ids) == set(book_ids), \
        "요구사항 원천·생성본 ID 불일치: 생성본 동기화 후 재검수 필요"
    return frozenset(source_ids)

