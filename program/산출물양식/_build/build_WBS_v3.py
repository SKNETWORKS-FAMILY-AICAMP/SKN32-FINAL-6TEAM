        "경로: [미확보] 2026-09-10 기준 총여유·임계·자원 평준화; 정세환, 09-15 Task 7",
        f"절삭: {cut_text(task)}",
        f"추적: {progress_text(task)}; {timing}; 범위처리={task['scope']}",
        f"표시: {source_state(task)}",
        f"미결: [미확보] {', '.join(dict.fromkeys(open_ids))}; 방법·담당·기한·미해결 조치는 C메모",
