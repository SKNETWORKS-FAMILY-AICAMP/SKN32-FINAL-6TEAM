def validate_tasks(tasks, issued_ids=ISSUED_IDS):
    ids = [task["id"] for task in tasks]
    assert all(type(task_id) is int and task_id > 0 for task_id in ids), \
        "Task ID는 양의 고정 정수여야 함"
    assert len(ids) == len(set(ids)), "Task ID 중복"
    assert set(ids) == set(issued_ids), \
        f"발급대장 불일치: 누락={sorted(set(issued_ids) - set(ids))}, 미등록={sorted(set(ids) - set(issued_ids))}"
    assert LEGACY_IDS <= set(ids), "기존 Task ID 삭제 금지"
    by_id = {task["id"]: task for task in tasks}

    for task in tasks:
        task_id = task["id"]
        assert task["state"] in STATES, f"Task {task_id}: 상태 오류"
        assert task["priority"] in PRIORITIES, f"Task {task_id}: 우선순위 오류"
        assert task["owner"] in OWNER_NAMES, f"Task {task_id}: 책임자 오류"
        assert task["start"] <= task["end"], f"Task {task_id}: 날짜 역전"
        assert task["output"] and task["criterion"], f"Task {task_id}: 인수 정보 없음"
        assert len(task["pred"]) == len(set(task["pred"])), f"Task {task_id}: 선행 중복"

        for predecessor in task["pred"]:
            assert predecessor in by_id, \
                f"Task {task_id}: 존재하지 않는 선행 Task ID {predecessor}"
            assert predecessor != task_id, f"Task {task_id}: 자기 자신이 선행"

        for req_id in task["req"]:
            assert req_id in REQ_IDS, \
                f"Task {task_id}: 존재하지 않는 요구사항 ID {req_id}"
        for dod_id in task["dod"]:
            assert dod_id in DOD_IDS, \
                f"Task {task_id}: 존재하지 않는 DoD ID {dod_id}"

        if task["scope"] != "유지":
            assert task["scope"] in ("보류", "연기", "제외", "폐기", "분할", "통합"), \
                f"Task {task_id}: 범위처리 값 오류"
            assert task["scope_reason"], f"Task {task_id}: 범위처리 사유·결정 기록 없음"
            if task["scope"] in ("보류", "연기", "제외", "폐기"):
                assert task["state"] != "완료", \
                    f"Task {task_id}: 범위 제외를 완료로 처리할 수 없음"

        if task["state"] == "완료":
            evidence = COMPLETIONS.get(task_id)
            assert evidence, f"Task {task_id}: 완료 판정 기록 없음"
            assert all(evidence.get(key) for key in ("산출물", "결과", "판정자", "판정일")), \
                f"Task {task_id}: 완료 판정 필수값 누락"
            assert evidence["결과"] == "통과", f"Task {task_id}: 미통과 작업"
            datetime.strptime(evidence["판정일"], "%Y-%m-%d")

    visiting, visited = set(), set()

    def visit(task_id):
        assert task_id not in visiting, f"선행 관계 순환: Task {task_id}"
        if task_id in visited:
            return
        visiting.add(task_id)
        for predecessor in by_id[task_id]["pred"]:
            visit(predecessor)
        visiting.remove(task_id)
        visited.add(task_id)

    for task_id in by_id:
        visit(task_id)
    return by_id

