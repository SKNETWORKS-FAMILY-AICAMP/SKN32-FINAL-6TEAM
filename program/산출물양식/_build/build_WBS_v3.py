FORBIDDEN_CODEPOINTS = {
    0x2014, 0x2013, 0x2192, 0x21D2, 0x2605, 0x2606,
    0x2713, 0x2714, 0x2715, 0x2717, 0x25B8, 0x2026,
    0x21C4, 0x2212,
} | set(range(0x2460, 0x2466))

def assert_safe_text(value):
    if isinstance(value, str):
        invalid = sorted({ord(char) for char in value if ord(char) in FORBIDDEN_CODEPOINTS})
        assert not invalid, f"문서 문자열 금지 문자: {[hex(code) for code in invalid]}"

