def coverage():
    fulfillment, verification = set(), set()
    for task in TASKS:
        if task["id"] in TRACE_IDS:
            continue
        if role(task) == "검증":
            verification.update(task["req"])
        else:
            fulfillment.update(task["req"])
    return (
        sorted(REQ_IDS - fulfillment),
        sorted(REQ_IDS - verification),
    )

