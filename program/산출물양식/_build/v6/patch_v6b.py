import sys
sys.stdout.reconfigure(encoding="utf-8")


def patch(path, pairs):
    s = open(path, encoding="utf-8").read()
    for a, b in pairs:
        if a not in s:
            raise SystemExit(f"[멈춤] {path}: 못 찾음 — {a[:60]}")
        s = s.replace(a, b, 1)
    open(path, "w", encoding="utf-8").write(s)
    print("고침:", path, len(pairs), "곳")


