    first = (
        "[미확보] %s: MoSCoW 미정; 결정 담당=정세환 R/A [제안]; "
        "기한=범위 검토; 대상 릴리스=%s; U-자원."
    ) % (req_id, release)
    g_lines = [first]
    if req_id == "REQ-001":
        g_lines.append(DOCUMENT_COMMON)
    g_lines.extend([
        "이유·미충족 영향: " + reason,
        "상위 목표·근거: " + source,
        (
            "요구 판단: [제안] 신규 요구와 AC; 기준선의 기존 결정을 대체하는 승인은 미확보."
            if proposal else
            "요구 판단: [결정] 인용한 v11 기준 요구; [제안] 본 개정의 AC 상세와 시험 명세."
        ),
        "DoD 연결: " + (
            P + " §12 / " + dod if dod else
            "[미확보] 직접 대응 번호. 요구 자체의 AC로 검수하며 번호 추가·변경은 U-상태에서 확정."
        ),
        "WBS 연결: [미확보] 구현 작업 ID와 검증 작업 ID를 각각 확보한다(U-상태).",
        "기준 시점·범위: 2026-09-10 로컬 작업 트리; 기록한 코드·DDL의 정적 확인에 한정.",
    ])
    if depends:
        g_lines.append("의존: " + "·".join(depends))
    if detail:
        g_lines.append("상세: " + detail)

    for index, _ in enumerate(acs, 1):
        ac_id = "%s/AC-%02d" % (req_id, index)
        state = IMPLEMENTATION.get(
            (req_id, index),
            "[미확보] 해당 AC 전체의 구현 증거; 미구현으로 단정하지 않는다(U-상태)."
        )
        g_lines.append(
            "%s | 구현: %s | 시험: 미실행(본 개정); "
            "명세=[제안] %s; 과거 실행 결과·판정자·판정일=[미확보] U-상태."
            % (ac_id, state, AC_CATALOG[ac_id])
        )
    for issue_id in issue_ids:
        g_lines.append(issue_id + ": " + OPEN_ITEMS[issue_id])

    REQ_META[req_id] = {
        "ac_count": len(acs),
        "issues": issue_ids,
        "depends": tuple(depends),
        "proposal": proposal,
    }
    return req_id, desc, "\n".join(f_lines), "\n".join(g_lines)


