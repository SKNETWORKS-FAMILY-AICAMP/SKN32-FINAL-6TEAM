def guard_sheet(sheet):
    """양식 질문 보존, G 비병합, D/G 및 원천 데이터 일치를 검사한다."""
    for position, expected in HEADER_VALUES.items():
        assert sheet.cell(*position).value == expected, "양식 질문·제목 변경: %s" % (position,)
    assert {
        str(rng) for rng in sheet.merged_cells.ranges if rng.min_row < 5
    } == HEADER_MERGES, "양식 머리글 병합 변경"

    for rng in sheet.merged_cells.ranges:
        if rng.min_col <= 7 <= rng.max_col and rng.max_row >= 5:
            raise AssertionError("본문 G열 병합 금지: " + str(rng))

    for r, item in enumerate(ALL_ITEMS, 5):
        saved = tuple(sheet.cell(r, c).value for c in range(4, 8))
        assert saved == item, "원천 내용과 셀 값 불일치: " + item[0]
        assert not isinstance(sheet.cell(r, 7), MergedCell), "G셀 병합"
        first = sheet.cell(r, 7).value.splitlines()[0]
        assert first.startswith(first.split()[0] + " " + sheet.cell(r, 4).value + ":")
    assert sheet["G5"].value.splitlines()[1].startswith("문서공통:")


