stamp=datetime.now(ZoneInfo('Asia/Seoul')).strftime('%Y-%m-%d_%H%M%S')
backup=BASE/'_backup'/(stamp+'_policy_review')
backup.mkdir(parents=True)
for p in sorted((BASE/'documents').glob('*.md')):
    shutil.copy2(p,backup/p.name)
    meta_raw,body=re.match(r'\A---\s*\n(.*?)\n---\s*\n(.*)\Z',p.read_text(encoding='utf-8'),re.S).groups()
    for old,new in changes.items(): body=body.replace(old,new)
    if p.name.startswith('t11'):
        body,n=re.subn(r'^## 승인 없이 실행하지 않는다\n.*?(?=^## |\Z)',
             '## 승인 없이 실행하지 않는다\n'+approval+'\n\n',body,flags=re.M|re.S)
        assert n==1
    meta=yaml.safe_load(meta_raw)
    sections=re.findall(r'^## ([^\n]+)\n(.*?)(?=^## |\Z)',body,re.M|re.S)
    assert len(sections)>=9
    meta['customer_answers']={title:re.split(r'(?<=[.!?])\s+',text.strip())[0] for title,text in sections}
    p.write_text('---\n'+yaml.safe_dump(meta,allow_unicode=True,sort_keys=False,width=1000)+'---\n\n'+body.strip()+'\n',encoding='utf-8')
print('backup',backup.relative_to(ROOT))
